features = []
seen_ids = set()


def add(fid, title, desc, cat, impl, adult=False, tags=None, payload=None):
    fid = fid.strip()
    assert re.fullmatch(r"[a-z0-9_.]+", fid), fid
    if fid in seen_ids:
        raise SystemExit("duplicate id: " + fid)
    seen_ids.add(fid)
    item = {
        "id": fid,
        "title": title,
        "desc": desc,
        "cat": cat,
        "impl": impl,
        "adult": adult,
    }
    if tags:
        item["tags"] = tags
    if payload:
        item["payload"] = payload
    features.append(item)


